create table public.admin_users (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  name text not null default '',
  role text not null default 'viewer'
    check (role in ('owner', 'admin', 'editor', 'viewer')),
  status text not null default 'active'
    check (status in ('active', 'suspended')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index admin_users_email_key on public.admin_users (lower(email));

create table public.apps (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique
    check (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  name text not null check (char_length(name) between 1 and 100),
  tagline text not null default '' check (char_length(tagline) <= 160),
  summary text not null default '' check (char_length(summary) <= 600),
  description text not null default '' check (char_length(description) <= 10000),
  category text not null default '기타' check (char_length(category) <= 60),
  platforms text[] not null default '{}',
  publication_status text not null default 'draft'
    check (publication_status in ('draft', 'in_review', 'published', 'archived')),
  product_status text not null default 'coming_soon'
    check (product_status in ('coming_soon', 'beta', 'live', 'maintenance', 'discontinued')),
  featured boolean not null default false,
  featured_rank integer,
  icon_url text,
  hero_image_url text,
  image_alt text not null default '' check (char_length(image_alt) <= 200),
  app_store_url text,
  play_store_url text,
  web_url text,
  seo_title text not null default '' check (char_length(seo_title) <= 70),
  seo_description text not null default '' check (char_length(seo_description) <= 180),
  version integer not null default 1 check (version > 0),
  published_at timestamptz,
  created_by uuid references auth.users(id) on delete set null,
  updated_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz,
  check (featured_rank is null or featured_rank >= 0),
  check (app_store_url is null or app_store_url ~ '^https://'),
  check (play_store_url is null or play_store_url ~ '^https://'),
  check (web_url is null or web_url ~ '^https://')
);

create index apps_admin_updated_idx on public.apps (updated_at desc)
  where deleted_at is null;
create index apps_public_published_idx on public.apps (published_at desc)
  where publication_status = 'published' and deleted_at is null;
create index apps_featured_idx on public.apps (featured_rank, published_at desc)
  where publication_status = 'published' and featured = true and deleted_at is null;

create table public.app_media (
  id uuid primary key default gen_random_uuid(),
  app_id uuid not null references public.apps(id) on delete cascade,
  media_type text not null check (media_type in ('icon', 'hero', 'screenshot')),
  url text not null check (url ~ '^https://'),
  alt text not null check (char_length(alt) between 1 and 200),
  width integer,
  height integer,
  sort_order integer not null default 0 check (sort_order >= 0),
  created_at timestamptz not null default now()
);

create index app_media_app_sort_idx on public.app_media (app_id, sort_order);

create table public.inquiries (
  id uuid primary key default gen_random_uuid(),
  inquiry_type text not null default 'project'
    check (inquiry_type in ('project', 'partnership', 'investment', 'other')),
  name text not null check (char_length(name) between 1 and 100),
  email text not null check (char_length(email) between 3 and 320),
  company text not null default '' check (char_length(company) <= 120),
  message text not null check (char_length(message) between 10 and 3000),
  status text not null default 'new'
    check (status in ('new', 'in_progress', 'resolved', 'spam')),
  privacy_consent boolean not null check (privacy_consent),
  consent_version text not null default '2026-07-18',
  source text not null default 'website',
  user_agent text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index inquiries_status_created_idx on public.inquiries (status, created_at desc);

create table public.audit_logs (
  id bigint generated by default as identity primary key,
  actor_id uuid references auth.users(id) on delete set null,
  action text not null,
  entity_type text not null,
  entity_id text,
  before_data jsonb,
  after_data jsonb,
  created_at timestamptz not null default now()
);

create index audit_logs_created_idx on public.audit_logs (created_at desc);
create index audit_logs_entity_idx on public.audit_logs (entity_type, entity_id, created_at desc);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger set_admin_users_updated_at
before update on public.admin_users
for each row execute function public.set_updated_at();

create trigger set_apps_updated_at
before update on public.apps
for each row execute function public.set_updated_at();

create trigger set_inquiries_updated_at
before update on public.inquiries
for each row execute function public.set_updated_at();

